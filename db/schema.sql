-- db/schema.sql — AI Safety Evaluation Platform
--
-- Creates all four tables needed by the pipeline.
-- Safe to run multiple times (CREATE TABLE IF NOT EXISTS).
--
-- Usage:
--   psql -d trust_safety -f db/schema.sql
--
-- Table overview:
--   ground_truth   — canonical labeled dataset rows (replaced on each ingest run)
--   predictions    — per-item LLM moderation decisions grouped by run_id
--   metrics        — aggregated confusion-matrix stats per run/prompt/category
--   error_analysis — individual FP and FN items for manual review


-- ── Ground Truth ──────────────────────────────────────────────────────────────
-- One row per comment/tweet from the source dataset.
-- Loaded fresh on each pipeline run (to_sql with if_exists="replace").
-- Jigsaw-specific columns are null for Davidson rows and vice-versa.
CREATE TABLE IF NOT EXISTS ground_truth (
    item_id         TEXT        PRIMARY KEY,
    text            TEXT        NOT NULL,
    -- Binary toxic label (present in both Jigsaw and Davidson after normalisation)
    toxic           SMALLINT,               -- 0/1, nullable
    -- Jigsaw multi-label columns (null for Davidson rows)
    severe_toxic    SMALLINT,
    obscene         SMALLINT,
    threat          SMALLINT,
    insult          SMALLINT,
    identity_hate   SMALLINT,
    -- Source tracking
    dataset_source  TEXT        NOT NULL    -- 'jigsaw' or 'davidson'
);


-- ── Predictions ───────────────────────────────────────────────────────────────
-- One row per (item, model, prompt_version) per run.
-- decision is NULL when moderation failed for that item (per-item isolation).
CREATE TABLE IF NOT EXISTS predictions (
    id              SERIAL      PRIMARY KEY,
    run_id          UUID        NOT NULL,
    item_id         TEXT        NOT NULL REFERENCES ground_truth(item_id),
    model_name      TEXT        NOT NULL,   -- e.g. 'gpt-4o-mini' or 'fixture'
    prompt_version  TEXT        NOT NULL,   -- 'zero_shot' or 'few_shot'
    decision        TEXT,                   -- 'toxic' | 'not_toxic' | NULL on failure
    confidence      FLOAT,                  -- [0.0, 1.0] | NULL on failure
    error_msg       TEXT                    -- populated when decision is NULL
);

CREATE INDEX IF NOT EXISTS idx_predictions_run_id
    ON predictions(run_id);
CREATE INDEX IF NOT EXISTS idx_predictions_model_prompt
    ON predictions(model_name, prompt_version);


-- ── Metrics ───────────────────────────────────────────────────────────────────
-- Aggregated evaluation results per run × prompt_version × category.
-- category = label name (e.g. 'toxic', 'severe_toxic') or 'overall'.
CREATE TABLE IF NOT EXISTS metrics (
    id              SERIAL      PRIMARY KEY,
    run_id          UUID        NOT NULL,
    prompt_version  TEXT        NOT NULL,
    category        TEXT        NOT NULL,
    tp              INT         NOT NULL DEFAULT 0,
    fp              INT         NOT NULL DEFAULT 0,
    fn              INT         NOT NULL DEFAULT 0,
    tn              INT         NOT NULL DEFAULT 0,
    precision       FLOAT       NOT NULL DEFAULT 0.0,
    recall          FLOAT       NOT NULL DEFAULT 0.0,
    f1              FLOAT       NOT NULL DEFAULT 0.0,
    fpr             FLOAT       NOT NULL DEFAULT 0.0,   -- false-positive rate
    fnr             FLOAT       NOT NULL DEFAULT 0.0    -- false-negative rate
);

CREATE INDEX IF NOT EXISTS idx_metrics_run_id
    ON metrics(run_id);
CREATE INDEX IF NOT EXISTS idx_metrics_run_prompt_category
    ON metrics(run_id, prompt_version, category);


-- ── Error Analysis ────────────────────────────────────────────────────────────
-- One row per false-positive or false-negative item per run.
-- Feeds the Error Analysis dashboard tab for human review.
CREATE TABLE IF NOT EXISTS error_analysis (
    id              SERIAL      PRIMARY KEY,
    run_id          UUID        NOT NULL,
    prompt_version  TEXT        NOT NULL,
    item_id         TEXT        NOT NULL,
    text            TEXT        NOT NULL,
    true_label      SMALLINT    NOT NULL,
    predicted_label TEXT        NOT NULL,   -- 'toxic' or 'not_toxic'
    confidence      FLOAT,
    error_type      TEXT        NOT NULL    -- 'FP' (over-flagged) or 'FN' (missed harm)
);

CREATE INDEX IF NOT EXISTS idx_error_analysis_run_id
    ON error_analysis(run_id);
CREATE INDEX IF NOT EXISTS idx_error_analysis_error_type
    ON error_analysis(error_type);


-- ── Threshold Metrics ─────────────────────────────────────────────────────────
-- Stores the full precision/recall/F1/FPR/FNR curve across confidence thresholds
-- for a given run × prompt_version × category.
--
-- Answers: "At what confidence cutoff should we call something toxic?"
-- Use this to plot precision-recall curves in Superset or to find the operating
-- point that hits a target recall (e.g. keep FNR below 5%).
--
-- Generated by evaluation.metrics.threshold_sweep() and written by pipeline.py.
CREATE TABLE IF NOT EXISTS threshold_metrics (
    id              SERIAL      PRIMARY KEY,
    run_id          UUID        NOT NULL,
    prompt_version  TEXT        NOT NULL,   -- 'zero_shot' or 'few_shot'
    category        TEXT        NOT NULL,   -- label name or 'overall'
    threshold       FLOAT       NOT NULL,   -- confidence cutoff, e.g. 0.5
    tp              INT         NOT NULL DEFAULT 0,
    fp              INT         NOT NULL DEFAULT 0,
    fn              INT         NOT NULL DEFAULT 0,
    tn              INT         NOT NULL DEFAULT 0,
    precision       FLOAT       NOT NULL DEFAULT 0.0,
    recall          FLOAT       NOT NULL DEFAULT 0.0,
    f1              FLOAT       NOT NULL DEFAULT 0.0,
    fpr             FLOAT       NOT NULL DEFAULT 0.0,
    fnr             FLOAT       NOT NULL DEFAULT 0.0
);

CREATE INDEX IF NOT EXISTS idx_threshold_metrics_run_id
    ON threshold_metrics(run_id);
CREATE INDEX IF NOT EXISTS idx_threshold_metrics_run_prompt_category
    ON threshold_metrics(run_id, prompt_version, category);


-- ── Adversarial Results ───────────────────────────────────────────────────────
-- Stores side-by-side moderation results for raw (obfuscated) text vs
-- normalized text, per obfuscation technique and model.
--
-- This is the core of the robustness analysis:
--   raw_decision   = what the model said about the obfuscated text
--   norm_decision  = what the model said after normalization
--
-- Key analytical question:
--   "Does normalization improve recall for this obfuscation type, or is
--    the LLM already robust to it?"
--
-- If norm_recall > raw_recall for homoglyphs but not for spacing, that is a
-- specific, publishable finding.
CREATE TABLE IF NOT EXISTS adversarial_results (
    id                  SERIAL      PRIMARY KEY,
    run_id              UUID        NOT NULL,
    item_id             TEXT        NOT NULL,   -- links to ground_truth.item_id
    model_name          TEXT        NOT NULL,   -- e.g. 'gpt-4o-mini'
    prompt_version      TEXT        NOT NULL,   -- 'zero_shot' or 'few_shot'
    obfuscation_type    TEXT        NOT NULL,   -- e.g. 'homoglyph', 'spacing'
    -- ── Text columns ──────────────────────────────────────────────────────────
    original_text       TEXT        NOT NULL,   -- clean original
    raw_text            TEXT        NOT NULL,   -- obfuscated variant
    normalized_text     TEXT        NOT NULL,   -- raw_text after normalize()
    -- ── Ground truth ──────────────────────────────────────────────────────────
    true_label          SMALLINT    NOT NULL,   -- 0 or 1
    -- ── Raw moderation (no preprocessing) ────────────────────────────────────
    raw_decision        TEXT,                   -- 'toxic' | 'not_toxic' | NULL
    raw_confidence      FLOAT,                  -- [0.0, 1.0] | NULL
    -- ── Normalized moderation (after preprocessing) ───────────────────────────
    norm_decision       TEXT,                   -- 'toxic' | 'not_toxic' | NULL
    norm_confidence     FLOAT,                  -- [0.0, 1.0] | NULL
    -- ── Derived outcome flags (computed at insert time) ───────────────────────
    -- raw_correct:  did the raw decision match the true label?
    -- norm_correct: did the normalized decision match the true label?
    -- norm_helped:  normalization flipped a wrong → right decision
    -- norm_hurt:    normalization flipped a right → wrong decision (rare but real)
    raw_correct         BOOLEAN,
    norm_correct        BOOLEAN,
    norm_helped         BOOLEAN,    -- raw_correct=FALSE AND norm_correct=TRUE
    norm_hurt           BOOLEAN     -- raw_correct=TRUE  AND norm_correct=FALSE
);

CREATE INDEX IF NOT EXISTS idx_adversarial_run_id
    ON adversarial_results(run_id);
CREATE INDEX IF NOT EXISTS idx_adversarial_obfuscation_type
    ON adversarial_results(obfuscation_type);
CREATE INDEX IF NOT EXISTS idx_adversarial_model_prompt
    ON adversarial_results(model_name, prompt_version);

-- Useful view: per-technique summary for the analysis layer
CREATE OR REPLACE VIEW adversarial_summary AS
SELECT
    obfuscation_type,
    model_name,
    prompt_version,
    COUNT(*)                                                        AS n,
    ROUND(AVG(CASE WHEN raw_correct  THEN 1.0 ELSE 0.0 END)::NUMERIC, 4) AS raw_accuracy,
    ROUND(AVG(CASE WHEN norm_correct THEN 1.0 ELSE 0.0 END)::NUMERIC, 4) AS norm_accuracy,
    ROUND(AVG(CASE WHEN norm_correct THEN 1.0 ELSE 0.0 END)::NUMERIC
        - AVG(CASE WHEN raw_correct  THEN 1.0 ELSE 0.0 END)::NUMERIC, 4) AS accuracy_delta,
    SUM(CASE WHEN norm_helped THEN 1 ELSE 0 END)                   AS norm_helped_count,
    SUM(CASE WHEN norm_hurt   THEN 1 ELSE 0 END)                   AS norm_hurt_count,
    -- Recall among truly toxic items only
    ROUND(
        SUM(CASE WHEN true_label = 1 AND raw_decision  = 'toxic' THEN 1.0 ELSE 0.0 END)
        / NULLIF(SUM(CASE WHEN true_label = 1 THEN 1 ELSE 0 END), 0)::NUMERIC
    , 4)                                                            AS raw_recall,
    ROUND(
        SUM(CASE WHEN true_label = 1 AND norm_decision = 'toxic' THEN 1.0 ELSE 0.0 END)
        / NULLIF(SUM(CASE WHEN true_label = 1 THEN 1 ELSE 0 END), 0)::NUMERIC
    , 4)                                                            AS norm_recall
FROM adversarial_results
GROUP BY obfuscation_type, model_name, prompt_version
ORDER BY accuracy_delta DESC;


-- ── Omni Moderation Results ───────────────────────────────────────────────────
-- Stores results from OpenAI's omni-moderation-latest endpoint.
-- One row per comment per run.
--
-- The omni endpoint returns:
--   flagged      — boolean, overall moderation decision
--   category scores — float [0,1] for each harm category
--
-- We store all category scores so we can:
--   1. Compare against Jigsaw ground-truth labels per category
--   2. Run threshold analysis (at what score cutoff do we match ground truth?)
--   3. Visualize which harm types the model is most/least confident about
CREATE TABLE IF NOT EXISTS omni_results (
    id                      SERIAL      PRIMARY KEY,
    run_id                  UUID        NOT NULL,
    item_id                 TEXT        NOT NULL,   -- FK to ground_truth.item_id
    -- Overall decision
    flagged                 BOOLEAN,                -- True = OpenAI flagged as harmful
    -- Category scores [0.0, 1.0] — higher = more harmful
    score_harassment        FLOAT,
    score_harassment_threatening FLOAT,
    score_hate              FLOAT,
    score_hate_threatening  FLOAT,
    score_illicit           FLOAT,
    score_illicit_violent   FLOAT,
    score_self_harm         FLOAT,
    score_self_harm_instructions FLOAT,
    score_self_harm_intent  FLOAT,
    score_sexual            FLOAT,
    score_sexual_minors     FLOAT,
    score_violence          FLOAT,
    score_violence_graphic  FLOAT,
    -- Category flags (boolean per category)
    flag_harassment         BOOLEAN,
    flag_hate               BOOLEAN,
    flag_self_harm          BOOLEAN,
    flag_sexual             BOOLEAN,
    flag_violence           BOOLEAN,
    -- Error tracking
    error_msg               TEXT        -- NULL on success
);

CREATE INDEX IF NOT EXISTS idx_omni_run_id
    ON omni_results(run_id);
CREATE INDEX IF NOT EXISTS idx_omni_item_id
    ON omni_results(item_id);
CREATE INDEX IF NOT EXISTS idx_omni_flagged
    ON omni_results(flagged);
